function platformSection(platform) {
  return `${platform.toUpperCase()} — ГДЕ ВЗЯТЬ ССЫЛКУ\n\n${channelInstructions[platform].map((step, i) => `${i + 1}. ${step}`).join('\n\n')}\n\n${socialInstructionText(platform)}`;
}

/** Public instructions only: no recipient-specific identity, tickets, or credentials. */
export function socialGuideFile(platform) {
  if (platform !== undefined && !Object.hasOwn(socialInstructions, platform)) {
    throw new RangeError('Неизвестная площадка для инструкции');
  }
  const selected = platform ? [platform] : Object.keys(socialInstructions);
  const text = `${journey}\n\n${'='.repeat(56)}\n\n${selected.map(platformSection).join(`\n\n${'='.repeat(56)}\n\n`)}\n\nВерсия инструкции: ${SOCIAL_GUIDE_VERSION}.\n`;
  return {
    filename: `kontent-zavod-${platform ? platform.toLowerCase() : 'creator-start'}-guide.txt`,
    mimeType: 'text/plain;charset=utf-8',
    text,
    caption: platform
      ? `${platform}: ссылка → готовность приложения → доступ → проверка статистики. Сохраните инструкцию; паролей и ключей в ней нет.`
      : 'Инструкция для креатора и продюсера: роль → ИИ/UGC → канал → доступ → статистика. Внутри — помощь по API, пример карточки и решение ошибок.',
  };
}

/** Use multipart upload so Telegram delivers an actual downloadable UTF-8 file. */
export function socialGuideForm(chatId, platform) {
  const guide = socialGuideFile(platform);
  const form = new FormData();
  form.set('chat_id', String(chatId));
  form.set('document', new Blob(['\uFEFF', guide.text], { type: guide.mimeType }), guide.filename);
  form.set('caption', guide.caption);
  form.set('disable_content_type_detection', 'true');
  return form;
}
